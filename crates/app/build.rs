//! Compiles the window's markup in `ui/` (Plan 0007 Phase 1); `main.rs` includes the result with
//! `slint::include_modules!()`.
//!
//! The phone's shell and gallery (`ui/mobile/`, Plan 0008) come in through the `@mobile` library
//! path. On Android, or with the `mobile` feature, it points at `ui/mobile`. Otherwise it points
//! at stubs written here from those files (Plan 0007 Phase 5, row AQ): the same exported globals,
//! and components with the same properties, callbacks and public functions but nothing inside,
//! so `main.slint` compiles unchanged while the desktop binary carries none of the phone's
//! markup.

use std::collections::HashMap;
use std::path::{Path, PathBuf};

fn main() {
    if let Err(err) = run() {
        // A build script reports through the build's own error output; there is no caller to
        // return a typed error to.
        eprintln!("slint compile of ui/main.slint failed: {err}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").ok_or("no manifest dir")?);
    let ui = manifest.join("ui");
    let real = std::env::var("CARGO_CFG_TARGET_OS").is_ok_and(|os| os == "android")
        || std::env::var_os("CARGO_FEATURE_MOBILE").is_some();
    let mobile = if real {
        ui.join("mobile")
    } else {
        let out = PathBuf::from(std::env::var_os("OUT_DIR").ok_or("no OUT_DIR")?).join("mobile");
        std::fs::create_dir_all(&out).map_err(|e| e.to_string())?;
        for name in ["shell.slint", "gallery.slint"] {
            let path = ui.join("mobile").join(name);
            let source = std::fs::read_to_string(&path).map_err(|e| format!("{name}: {e}"))?;
            std::fs::write(out.join(name), stub(&source, &ui)?).map_err(|e| e.to_string())?;
            println!("cargo:rerun-if-changed={}", path.display());
        }
        out
    };
    println!("cargo:rerun-if-changed=ui");
    let config = slint_build::CompilerConfiguration::new()
        .with_library_paths(HashMap::from([("mobile".to_string(), mobile)]));
    slint_build::compile_with_config("ui/main.slint", config).map_err(|e| e.to_string())
}

/// A `.slint` file without its markup: its `../` imports (with absolute paths), its exported
/// globals as they are, and each exported component's interface with empty bodies.
fn stub(source: &str, ui: &Path) -> Result<String, String> {
    let code = strip_comments(source);
    let mut out = String::from("// Generated by build.rs from ui/mobile: the interface only.\n");
    let mut rest = code.as_str();
    while let Some(start) = next_item(rest) {
        rest = &rest[start..];
        if rest.starts_with("import") {
            let end = rest.find(';').ok_or("unterminated import")? + 1;
            let item = &rest[..end];
            if let Some(at) = item.find("\"../") {
                let path = ui.join(&item[at + 4..item.len() - 2]);
                let path = path.to_string_lossy().replace('\\', "/");
                out.push_str(&format!("{}\"{path}\";\n", &item[..at]));
            }
            rest = &rest[end..];
        } else {
            let open = rest.find('{').ok_or("item without a body")?;
            let close = open + matching(&rest[open..])?;
            let head = rest[..open].trim();
            if head.starts_with("export global") {
                out.push_str(&rest[..=close]);
                out.push('\n');
            } else if head.starts_with("export component") {
                out.push_str(head);
                out.push_str(" {\n");
                for line in interface(&rest[open + 1..close])? {
                    out.push_str("    ");
                    out.push_str(&line);
                    out.push('\n');
                }
                out.push_str("}\n");
            }
            rest = &rest[close + 1..];
        }
    }
    Ok(out)
}

/// The offset of the next top-level item: an import, a component, a global or a struct.
fn next_item(code: &str) -> Option<usize> {
    let mut at = 0;
    for line in code.split_inclusive('\n') {
        let word = line.trim_start();
        if ["import", "export", "component", "global", "struct", "enum"]
            .iter()
            .any(|kw| word.starts_with(kw))
            && line.len() == word.len()
        {
            return Some(at);
        }
        at += line.len();
    }
    None
}

/// The component body's own declarations, one per entry, with no bindings and empty functions.
fn interface(body: &str) -> Result<Vec<String>, String> {
    let mut found = Vec::new();
    let mut depth = 0usize;
    let mut i = 0;
    let bytes = body.as_bytes();
    while i < bytes.len() {
        match bytes[i] {
            b'{' => depth += 1,
            b'}' => depth = depth.saturating_sub(1),
            b'"' => i += skip_string(&body[i..]),
            _ if depth == 0 && starts_word(body, i) => {
                let rest = &body[i..];
                if let Some(decl) = property(rest) {
                    found.push(decl);
                } else if rest.starts_with("callback ") || rest.starts_with("pure callback ") {
                    let end = rest.find(';').ok_or("unterminated callback")?;
                    let decl = &rest[..end];
                    if decl.contains("<=>") {
                        return Err(format!("aliased callback: {decl}"));
                    }
                    found.push(format!("{};", squeeze(decl)));
                } else if rest.starts_with("public function ")
                    || rest.starts_with("pure public function ")
                {
                    let open = rest.find('{').ok_or("function without a body")?;
                    let head = squeeze(&rest[..open]);
                    let value = match head.split("->").nth(1).map(str::trim) {
                        None => String::new(),
                        Some("bool") => "return false;".into(),
                        Some("int") | Some("float") => "return 0;".into(),
                        Some("length") => "return 0px;".into(),
                        Some("string") => "return \"\";".into(),
                        Some(other) => return Err(format!("no default for {other}")),
                    };
                    found.push(format!("{head} {{ {value} }}"));
                }
            }
            _ => {}
        }
        i += 1;
    }
    Ok(found)
}

/// `in`, `out` or `in-out property <T> name`, without its binding.
fn property(rest: &str) -> Option<String> {
    let kind = ["in-out property", "in property", "out property"]
        .into_iter()
        .find(|kind| rest.starts_with(kind))?;
    let after = rest[kind.len()..].trim_start();
    let ty_end = matching_angle(after)?;
    let ty = &after[..=ty_end];
    let name: String = after[ty_end + 1..]
        .trim_start()
        .chars()
        .take_while(|c| c.is_alphanumeric() || *c == '-' || *c == '_')
        .collect();
    Some(format!("{kind} {ty} {name};"))
}

fn starts_word(text: &str, i: usize) -> bool {
    i == 0 || !text.as_bytes()[i - 1].is_ascii_alphanumeric() && text.as_bytes()[i - 1] != b'-'
}

fn squeeze(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// The length of a string literal starting at `text[0]`, less one.
fn skip_string(text: &str) -> usize {
    let mut escaped = false;
    for (i, c) in text.char_indices().skip(1) {
        match c {
            '\\' if !escaped => escaped = true,
            '"' if !escaped => return i,
            _ => escaped = false,
        }
    }
    text.len() - 1
}

/// The offset of the brace closing the one at `text[0]`.
fn matching(text: &str) -> Result<usize, String> {
    let mut depth = 0usize;
    let mut i = 0;
    let bytes = text.as_bytes();
    while i < bytes.len() {
        match bytes[i] {
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    return Ok(i);
                }
            }
            b'"' => i += skip_string(&text[i..]),
            _ => {}
        }
        i += 1;
    }
    Err("unbalanced braces".into())
}

/// The offset of the `>` closing the `<` at `text[0]`.
fn matching_angle(text: &str) -> Option<usize> {
    let mut depth = 0usize;
    for (i, c) in text.char_indices() {
        match c {
            '<' => depth += 1,
            '>' => {
                depth -= 1;
                if depth == 0 {
                    return Some(i);
                }
            }
            _ => {}
        }
    }
    None
}

/// The source without `//` and `/* */` comments (strings kept).
fn strip_comments(source: &str) -> String {
    let mut out = String::with_capacity(source.len());
    let mut chars = source.chars().peekable();
    let mut in_string = false;
    let mut escaped = false;
    while let Some(c) = chars.next() {
        if in_string {
            out.push(c);
            match c {
                '\\' if !escaped => escaped = true,
                '"' if !escaped => in_string = false,
                _ => escaped = false,
            }
            continue;
        }
        match (c, chars.peek()) {
            ('"', _) => {
                in_string = true;
                out.push(c);
            }
            ('/', Some('/')) => {
                for c in chars.by_ref() {
                    if c == '\n' {
                        out.push('\n');
                        break;
                    }
                }
            }
            ('/', Some('*')) => {
                chars.next();
                let mut last = ' ';
                for c in chars.by_ref() {
                    if last == '*' && c == '/' {
                        break;
                    }
                    last = c;
                }
            }
            _ => out.push(c),
        }
    }
    out
}
